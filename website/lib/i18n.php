/**
 * Site chrome EN/HU. User-generated news/forum posts stay in the language they were written.
 */

function current_lang(): string
{
    return $GLOBALS['EG_LANG'] ?? 'en';
}

function is_hu(): bool
{
    return current_lang() === 'hu';
}

function t(string $key, array $vars = []): string
{
    static $cat = null;
    if ($cat === null) {
        $cat = i18n_catalog();
    }
    $lang = current_lang();
    $s = $cat[$lang][$key] ?? $cat['en'][$key] ?? $key;
    foreach ($vars as $k => $v) {
        $s = str_replace('{' . $k . '}', (string) $v, $s);
    }
    return $s;
}

function lang_switch_url(string $lang): string
{
    $path = (string) (parse_url($_SERVER['REQUEST_URI'] ?? '/', PHP_URL_PATH) ?: '/');
    $q = $_GET;
    $q['lang'] = $lang;
    return $path . '?' . http_build_query($q);
}

function init_lang(): void
{
    $allowed = ['en', 'hu'];
    $picked = null;
    if (isset($_GET['lang']) && in_array($_GET['lang'], $allowed, true)) {
        $picked = $_GET['lang'];
        $secure = (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off');
        setcookie('eg_lang', $picked, [
            'expires' => time() + 86400 * 400,
            'path' => '/',
            'secure' => $secure,
            'httponly' => true,
            'samesite' => 'Lax',
        ]);
        $_SESSION['eg_lang'] = $picked;
        if (strtoupper((string) ($_SERVER['REQUEST_METHOD'] ?? 'GET')) === 'GET') {
            $q = $_GET;
            unset($q['lang']);
            $path = (string) (parse_url($_SERVER['REQUEST_URI'] ?? '/', PHP_URL_PATH) ?: '/');
            $qs = http_build_query($q);
            redirect($path . ($qs !== '' ? '?' . $qs : ''));
        }
    }
    if ($picked === null && !empty($_SESSION['eg_lang']) && in_array($_SESSION['eg_lang'], $allowed, true)) {
        $picked = $_SESSION['eg_lang'];
    }
    if ($picked === null && !empty($_COOKIE['eg_lang']) && in_array($_COOKIE['eg_lang'], $allowed, true)) {
        $picked = $_COOKIE['eg_lang'];
        $_SESSION['eg_lang'] = $picked;
    }
    if ($picked === null) {
        $al = strtolower((string) ($_SERVER['HTTP_ACCEPT_LANGUAGE'] ?? ''));
        $picked = (preg_match('/(?:^|,)\s*hu\b/', $al) === 1) ? 'hu' : 'en';
    }
    $GLOBALS['EG_LANG'] = $picked;
}

